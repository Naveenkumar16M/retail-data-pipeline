
# ============================================================
# RETAIL DATA ETL PIPELINE - LOAD
# Purpose:
# 1. Read validated CSV records
# 2. Create the SQLite database table if required
# 3. Validate records before loading
# 4. Insert valid records into SQLite
# 5. Verify loaded data
# 6. Handle errors using rollback and logging
# ============================================================


# STEP 1: Import required libraries
# pandas   -> Read and process CSV data
# sqlite3  -> Connect to SQLite database
# logging  -> Record pipeline execution and errors
# pathlib  -> Create directories

import pandas as pd
import sqlite3
import logging
from pathlib import Path


# STEP 2: Configure logging
# Create the logs folder if it does not exist.
# Save execution messages and errors in logs/etl.log.
# filemode="a" appends logs instead of overwriting them.

Path("logs").mkdir(exist_ok=True)

logging.basicConfig(
    filename="logs/etl.log",
    filemode="a",
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s"
)

logging.info("ETL loading process started")


# STEP 3: Read validated CSV data
# This file is generated by extract.py.
# It contains records that passed data quality checks.

valid_df = pd.read_csv("data/valid_df.csv")

logging.info("Valid CSV records: %d", len(valid_df))


# STEP 4: Select required database columns
# The CSV also contains an error_reason column.
# SQLite orders table requires only these six columns.

db_df = valid_df[
    [
        "order_id",
        "order_date",
        "customer_id",
        "product",
        "quantity",
        "unit_price"
    ]
]


# STEP 5: Convert DataFrame rows into tuples
# index=False excludes the Pandas row index.
# name=None creates ordinary Python tuples.
# executemany() accepts these tuples for bulk loading.

records = list(
    db_df.itertuples(index=False, name=None)
)

logging.info("Records prepared for loading: %d", len(records))


# STEP 6: Connect to SQLite database
# The database file is created automatically if absent.

conn = sqlite3.connect("data/retail.db")

logging.info("Database connected successfully")

cursor = conn.cursor()

logging.info("Cursor created successfully")


try:

    # STEP 7: Create orders table if it does not exist
    # order_id is the primary key.
    # NOT NULL prevents missing values in required columns.

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS orders (
            order_id INTEGER PRIMARY KEY,
            order_date TEXT NOT NULL,
            customer_id TEXT NOT NULL,
            product TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price REAL NOT NULL
        )
    """)

    logging.info("Orders table verified")


    # STEP 8: Validate unit prices before loading
    # Each tuple has six values.
    # Index 5 contains unit_price.
    # Raise ValueError if any price is negative.

    for row in records:
        if row[5] < 0:
            raise ValueError(
                f"Invalid unit price for order {row[0]}"
            )

    logging.info("Unit price validation passed")


    # STEP 9: Bulk insert records into SQLite
    # executemany() processes all records.
    # INSERT OR IGNORE skips duplicate primary keys.
    # This helps prevent duplicate rows during reruns.

    cursor.executemany(
        """
        INSERT OR IGNORE INTO orders
        (
            order_id,
            order_date,
            customer_id,
            product,
            quantity,
            unit_price
        )
        VALUES (?, ?, ?, ?, ?, ?)
        """,
        records
    )

    # Count newly inserted records before another SQL statement.
    inserted_count = cursor.rowcount

    logging.info("New records inserted: %d", inserted_count)


    # STEP 10: Commit the transaction
    # Save all successful inserts permanently.

    conn.commit()

    logging.info("Transaction committed successfully")


    # STEP 11: Verify total database records
    # fetchone()[0] extracts the COUNT(*) value.

    cursor.execute("SELECT COUNT(*) FROM orders")

    total_records = cursor.fetchone()[0]

    logging.info(
        "Total records in database: %d",
        total_records
    )

    print("Total records:", total_records)


    # STEP 12: Fetch and display loaded records
    # ORDER BY sorts results by order_id.

    cursor.execute("""
        SELECT
            order_id,
            product,
            quantity,
            unit_price
        FROM orders
        ORDER BY order_id
    """)

    rows = cursor.fetchall()

    for row in rows:
        print(row)


# STEP 13: Handle validation errors
# Roll back uncommitted database changes.
# logging.exception records the error and traceback.

except ValueError:
    conn.rollback()
    logging.exception("Validation failed - rollback performed")


# STEP 14: Handle SQLite database errors
# Roll back the transaction if loading fails.

except sqlite3.Error:
    conn.rollback()
    logging.exception("Database loading failed - rollback performed")


# STEP 15: Always close the database connection
# finally runs whether the process succeeds or fails.

finally:
    conn.close()
    logging.info("Database connection closed")
